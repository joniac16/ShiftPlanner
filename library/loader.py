"""Read and write the project's JSON files.

Reading functions turn the JSON files into the dataclasses of `library.models`
and check that the data is coherent. Every function takes the data folder as a
parameter (`data` by default), so tests can use their own data.

    data/
      source/   lines.json, operators.json, demands.json, availabilities.json
      output/   <period>.json   proposals generated by the solver
      history/  <period>.json   approved weeks
"""

import json
import shutil
from pathlib import Path

from library.models import (
    Assignment,
    Availability,
    Line,
    LineDemand,
    Operator,
    PlanningInput,
    RestrictedGroup,
    Shift,
    Staff,
    WeekAllocation,
)
from library.periods import parse_period, sort_periods

DEFAULT_DATA_DIR = Path("data")

TRAINED_ROLES = ("specialist", "qualified")
ROLES = TRAINED_ROLES + ("assistant",)


class DataError(ValueError):
    """The data files are missing, malformed or inconsistent."""


# --- Helpers -------------------------------------------------------------------


def _read_json(path: Path):
    try:
        with open(path, encoding="utf-8") as f:
            return json.load(f)
    except FileNotFoundError:
        raise DataError(f"File not found: {path}") from None
    except json.JSONDecodeError as e:
        raise DataError(f"Invalid JSON in {path}: {e}") from None


def _check_unique(ids: list[str], what: str, source: Path) -> None:
    seen = set()
    for item_id in ids:
        if item_id in seen:
            raise DataError(f"Duplicate {what} '{item_id}' in {source}")
        seen.add(item_id)


def _check_period(period: str) -> None:
    try:
        parse_period(period)
    except ValueError:
        raise DataError(f"Invalid period '{period}' (expected e.g. '2027-W5')") from None


def _week_data(path: Path, period: str) -> list:
    """Return the block of a weekly file (demands/availabilities) for a period."""
    _check_period(period)
    data = _read_json(path)
    if period not in data:
        raise DataError(f"Period '{period}' not found in {path}")
    return data[period]


# --- Master data ---------------------------------------------------------------


def load_lines(data_dir: Path | str = DEFAULT_DATA_DIR) -> dict[str, Line]:
    """Read source/lines.json. Returns line id -> Line.

    Lines of the same restricted group must declare the same limits.
    """
    path = Path(data_dir) / "source" / "lines.json"
    raw = _read_json(path)
    _check_unique([item["id"] for item in raw], "line id", path)

    lines = {}
    groups: dict[str, RestrictedGroup] = {}
    for item in raw:
        group = None
        if "restricted_group" in item:
            group = RestrictedGroup(**item["restricted_group"])
            if group.max_consecutive_weeks < 1 or group.min_rest_weeks < 1:
                raise DataError(f"Restricted group '{group.id}' on line {item['id']}: limits must be at least 1")
            if group.id in groups and groups[group.id] != group:
                raise DataError(
                    f"Restricted group '{group.id}' has different limits on line {item['id']} "
                    f"than on other lines of the group"
                )
            groups[group.id] = group
        lines[item["id"]] = Line(id=item["id"], name=item["name"], restricted_group=group)
    return lines


def load_operators(data_dir: Path | str = DEFAULT_DATA_DIR) -> dict[str, Operator]:
    """Read source/operators.json. Returns operator id -> Operator."""
    path = Path(data_dir) / "source" / "operators.json"
    raw = _read_json(path)
    _check_unique([item["id"] for item in raw], "operator id", path)

    operators = {}
    for item in raw:
        training = item.get("lines", {})
        for line_id, role in training.items():
            if role not in TRAINED_ROLES:
                raise DataError(
                    f"Operator {item['id']} has invalid level '{role}' on line {line_id} "
                    f"(expected one of {', '.join(TRAINED_ROLES)})"
                )
        operators[item["id"]] = Operator(id=item["id"], name=item["name"], lines=training)
    return operators


# --- Weekly data ---------------------------------------------------------------


def load_demands(period: str, data_dir: Path | str = DEFAULT_DATA_DIR) -> list[LineDemand]:
    """Read the needs of each line for one week from source/demands.json."""
    path = Path(data_dir) / "source" / "demands.json"
    raw = _week_data(path, period)
    _check_unique([item["line"] for item in raw], f"line in {period}", path)

    demands = []
    for item in raw:
        _check_unique([s["name"] for s in item["shifts"]], f"shift of line {item['line']} in {period}", path)
        shifts = []
        for s in item["shifts"]:
            unknown = set(s["staff"]) - set(ROLES)
            if unknown:
                raise DataError(f"Unknown role(s) {sorted(unknown)} in {period}, line {item['line']}, shift {s['name']}")
            if any(not isinstance(n, int) or n < 0 for n in s["staff"].values()):
                raise DataError(f"Staff numbers must be non-negative integers in {period}, line {item['line']}, shift {s['name']}")
            shifts.append(Shift(name=s["name"], staff=Staff(**s["staff"])))
        demands.append(LineDemand(line=item["line"], shifts=shifts))
    return demands


def load_availabilities(period: str, data_dir: Path | str = DEFAULT_DATA_DIR) -> dict[str, Availability]:
    """Read the shifts each operator can cover in one week from source/availabilities.json.

    Returns operator id -> Availability. Operators not listed are not available.
    """
    path = Path(data_dir) / "source" / "availabilities.json"
    raw = _week_data(path, period)
    _check_unique([item["operator"] for item in raw], f"operator in {period}", path)
    return {item["operator"]: Availability(operator=item["operator"], shifts=list(item["shifts"])) for item in raw}


# --- Allocations ---------------------------------------------------------------


def load_allocation(path: Path | str) -> WeekAllocation:
    """Read one allocation file (a proposal in output/ or an approved week in history/)."""
    path = Path(path)
    raw = _read_json(path)
    period = raw["period"]
    _check_period(period)
    if path.stem != period:
        raise DataError(f"File {path} contains period '{period}', expected '{path.stem}'")

    assignments = []
    for a in raw["assignments"]:
        if a["role"] not in ROLES:
            raise DataError(f"Invalid role '{a['role']}' for operator {a['operator']} in {path}")
        assignments.append(Assignment(operator=a["operator"], line=a["line"], shift=a["shift"], role=a["role"]))
    _check_unique([a.operator for a in assignments], "operator assignment", path)
    return WeekAllocation(period=period, assignments=assignments)


def load_history(data_dir: Path | str = DEFAULT_DATA_DIR) -> list[WeekAllocation]:
    """Read all approved weeks in history/, oldest first. Empty list if there are none."""
    folder = Path(data_dir) / "history"
    files = {p.stem: p for p in folder.glob("*.json")}
    for period in files:
        _check_period(period)
    return [load_allocation(files[period]) for period in sort_periods(list(files))]


def save_allocation(allocation: WeekAllocation, path: Path | str) -> Path:
    """Write an allocation as JSON, one assignment per line."""
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    rows = ",\n".join("    " + json.dumps(a.__dict__, ensure_ascii=False) for a in allocation.assignments)
    body = f'{{\n  "period": {json.dumps(allocation.period)},\n  "assignments": [\n{rows}\n  ]\n}}\n'
    path.write_text(body, encoding="utf-8")
    return path


def save_proposal(allocation: WeekAllocation, data_dir: Path | str = DEFAULT_DATA_DIR) -> Path:
    """Write a proposal to output/<period>.json (overwrites it if it exists)."""
    return save_allocation(allocation, Path(data_dir) / "output" / f"{allocation.period}.json")


def approve(period: str, data_dir: Path | str = DEFAULT_DATA_DIR) -> Path:
    """Copy output/<period>.json to history/<period>.json after validating it.

    The proposal is validated against the master data and the week's demand and
    availability, so manual edits cannot slip errors into the history.
    """
    data_dir = Path(data_dir)
    source = data_dir / "output" / f"{period}.json"
    allocation = load_allocation(source)
    validate_allocation(allocation, load_planning_input(period, data_dir))
    target = data_dir / "history" / f"{period}.json"
    target.parent.mkdir(parents=True, exist_ok=True)
    shutil.copyfile(source, target)
    return target


# --- Everything together -------------------------------------------------------


def validate_planning_input(data: PlanningInput) -> None:
    """Check that the files fit together (ids referenced in one file exist in the others)."""
    for operator in data.operators.values():
        for line_id in operator.lines:
            if line_id not in data.lines:
                raise DataError(f"Operator {operator.id} is trained on line {line_id}, which does not exist")
    for demand in data.demands:
        if demand.line not in data.lines:
            raise DataError(f"Demand for {data.period} refers to line {demand.line}, which does not exist")
    for operator_id in data.availabilities:
        if operator_id not in data.operators:
            raise DataError(f"Availability for {data.period} refers to operator {operator_id}, which does not exist")


def validate_allocation(allocation: WeekAllocation, data: PlanningInput) -> None:
    """Check that an allocation respects the week's demand, availability and training.

    Restricted groups are checked by the solver, not here.
    """
    if allocation.period != data.period:
        raise DataError(f"Allocation is for {allocation.period}, planning data is for {data.period}")

    needed = {
        (d.line, s.name, role): getattr(s.staff, role)
        for d in data.demands for s in d.shifts for role in ROLES
    }
    covered: dict[tuple[str, str, str], int] = {}
    for a in allocation.assignments:
        if a.operator not in data.operators:
            raise DataError(f"Unknown operator {a.operator}")
        available = data.availabilities.get(a.operator)
        if available is None or a.shift not in available.shifts:
            raise DataError(f"Operator {a.operator} is not available on shift {a.shift} in {data.period}")
        level = data.operators[a.operator].lines.get(a.line, "assistant")
        if level != a.role:
            raise DataError(f"Operator {a.operator} is {level} on line {a.line}, not {a.role}")
        key = (a.line, a.shift, a.role)
        if key not in needed:
            raise DataError(f"Line {a.line} does not run shift {a.shift} in {data.period}")
        covered[key] = covered.get(key, 0) + 1

    for (line, shift, role), n in needed.items():
        if covered.get((line, shift, role), 0) != n:
            raise DataError(
                f"Line {line}, shift {shift} needs {n} {role}(s), got {covered.get((line, shift, role), 0)}"
            )


def load_planning_input(period: str, data_dir: Path | str = DEFAULT_DATA_DIR) -> PlanningInput:
    """Load and validate everything the solver needs to plan `period`.

    The history only includes approved weeks before `period`.
    """
    _check_period(period)
    start = parse_period(period)
    history = [w for w in load_history(data_dir) if parse_period(w.period) < start]
    data = PlanningInput(
        period=period,
        lines=load_lines(data_dir),
        operators=load_operators(data_dir),
        demands=load_demands(period, data_dir),
        availabilities=load_availabilities(period, data_dir),
        history=history,
    )
    validate_planning_input(data)
    return data
